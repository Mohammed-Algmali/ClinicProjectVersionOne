# auth/schemas.py
from typing import Optional
from pydantic import BaseModel


# ==============================================================================
# 1. مخطط إرجاع رمز الدخول (Token Response)
# ==============================================================================
class Token(BaseModel):
    """
    شكل استجابة تسجيل الدخول الناجح التي تُرسل للفرونت إند
    """
    access_token: str
    # رمز الـ JWT المشفر الذي يحمله المستخدم في الترويسة (Header) لإثبات هويته

    token_type: str = "bearer"
    # نوع الرمز المعتمد برمجياً (دائماً bearer في معايير OAuth2)


# ==============================================================================
# 2. مخطط فك تشفير الرمز واستخراج البيانات (Token Payload)
# ==============================================================================
class TokenData(BaseModel):
    """
    البيانات المستخرجة من داخل الـ JWT بعد فك تشفيره للتحقق من هوية صاحب الطلب
    """
    user_id: Optional[int] = None
    # المعرف الأساسي للمستخدم المستخرج من الرمز

    username: Optional[str] = None
    # اسم المستخدم صاحب الجلسة الحالية

    role_id: Optional[int] = None
    # رقم دور وصلاحية المستخدم للتحقق من وصوله للمسارات المحمية


# ==============================================================================
# 3. مخطط طلب تسجيل الدخول المباشر (Login Request)
# ==============================================================================
class LoginRequest(BaseModel):
    """
    بيانات اعتماد الدخول التي يرسلها المستخدم من الشاشة
    """
    username: str
    # اسم المستخدم المدخل

    password: str
    # كلمة المرور المدخلة