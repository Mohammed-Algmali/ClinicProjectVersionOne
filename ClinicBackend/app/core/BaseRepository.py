# system_core/base_repository.py
from typing import Any, Dict, Generic, List, Optional, Type, TypeVar
from sqlalchemy import select
from sqlalchemy.orm import Session
from app.core.database import Base
from pydantic import BaseModel
# تعريف متغير نوع عام (Generic TypeVar) يمثل أي جدول من جداول قاعدة البيانات
ModelType = TypeVar("ModelType", bound=Base)


class BaseRepository(Generic[ModelType]):
  """كلاس الأب العام لجميع المستودعات في المنظومة الطبية:

  يرثه أي مستودع (مرضى، أطباء، منشآت، أدوار...) ليوفر له العمليات الأساسية
  تلقائياً دون تكرار.
  """

  # -------------------------------------------------------------------------
  # دالة البناء (Constructor)
  # -------------------------------------------------------------------------
  def __init__(self, model: Type[ModelType], db: Session):
    self.model = model
    # نوع الجدول المحدد الذي سيعمل عليه المستودع الابن (مثل: جدول Role أو جدول Facility)

    self.db = db
    # جلسة الاتصال بقاعدة البيانات المشتركة بين كل دوال الكلاس

  # =========================================================================
  # 1. دالة البحث برقم المعرّف (get_by_id)
  #
  # • الوظيفة: البحث عن سجل محدد بواسطة المفتاح الأساسي (Primary Key).
  # • متى تستخدمها؟
  #   - عند تعديل أي عنصر (للتأكد من وجوده قبل التعديل).
  #   - عند عرض شاشة تفاصيل مريض أو دور محدد.
  #   - عند ربط الجداول ببعضها (مثال: التأكد من وجود الدور برقم RoleId قبل ربطه بمستخدم).
  # • مثال عملي:
  #   role = repo.get_by_id(1)
  # =========================================================================
  def get_by_id(self, id: Any) -> Optional[ModelType]:
    return self.db.get(self.model, id)
    # ترجع كائن السجل إذا وُجد، أو ترجع None إذا كان الرقم غير موجود في الجدول

  # =========================================================================
  # 2. دالة جلب جميع السجلات (get_all)
  #
  # • الوظيفة: جلب قائمة السجلات المخزنة مع تقسيمها لصفحات (Pagination).
  # • متى تستخدمها؟
  #   - عند عرض الجداول الطويلة في الشاشات (مثل: جدول المرضى، جدول الفواتير).
  #   - عند ملء القوائم المنسدلة (Dropdowns) في شاشات الإدخال.
  # • مثال عملي:
  #   all_roles = repo.get_all(skip=0, limit=20)
  # =========================================================================
  def get_all(self, skip: int = 0, limit: int = 100) -> List[ModelType]:
    statement = select(self.model).offset(skip).limit(limit)
    # صياغة الاستعلام: SELECT * FROM table OFFSET skip LIMIT limit

    return list(self.db.scalars(statement).all())
    # تنفيذ الاستعلام وإرجاع قائمة بالكائنات المحفوظة

  # =========================================================================
  # 3. دالة الإنشاء الفردي المباشر (create)
  #
  # • الوظيفة: إضافة وحفظ سجل جديد نهائياً في قاعدة البيانات مع تثبيت (Commit) فوري.
  # • متى تستخدمها؟
  #   - في العمليات البسيطة المستقلة (التي لا تحتاج لإنشاء جداول أخرى في نفس اللحظة).
  # • مثال عملي:
  #   إضافة دور وظيفي جديد (Role)، أو إضافة دواء جديد لدليل الأدوية، أو إنشاء قسم طبي جديد.
  # =========================================================================
  def create(self, obj_data: Dict[str, Any]) -> ModelType:
    db_obj = self.model(**obj_data)
    # تفريغ مفاتيح وقيم القاموس مباشرة داخل أعمدة الجدول

    self.db.add(db_obj)
    # وضع الكائن في قائمة الانتظار (Staging)

    self.db.commit()
    # تثبيت العملية فوراً في قاعدة البيانات

    self.db.refresh(db_obj)
    # قراءة السجل مجدداً لتحديث المعرف الأساسي وتواريخ الإنشاء التلقائية

    return db_obj
    # إرجاع الكائن المكتمل بعد حفظه

  # =========================================================================
  # 4. دالة الإنشاء بدون تثبيت (create_without_commit)
  #
  # • الوظيفة: إنشاء السجل وتوليد معرّفه (ID) فوراً دون تنفيذ Commit نهائي.
  # • متى تستخدمها؟ [دالة جوهرية للعمليات المركبة Transactions]
  #   - عندما تحتاج لإنشاء أكثر من جدول مترابط في نفس اللحظة، وتحتاج لـ ID الأول
  #     لربطه بالثاني قبل إغلاق العملية.
  # • مثال عملي:
  #   تسجيل منشأة جديدة؛ ننشئ المستخدم أولاً بهذه الدالة لنحصل على UserId فوراً،
  #   ثم نربطه بالمنشأة، وننشئ الفرع، وفي الأخير ننفذ أمر commit() واحد للجميع.
  # =========================================================================
  def create_without_commit(self, obj_data: Dict[str, Any]) -> ModelType:
    db_obj = self.model(**obj_data)
    # تجهيز الكائن في الذاكرة

    self.db.add(db_obj)
    # وضعه في جلسة الحفظ

    self.db.flush()
    # توليد المفتاح الأساسي (ID) فوراً في الذاكرة مع بقاء المعاملة مفتوحة دون حفظ نهائي

    return db_obj
    # إرجاع الكائن ومعه رقمه التعريفي الجديد لاستخدامه في الجداول التالية

  # =========================================================================
  # 5. دالة التعديل والتحديث (update)
  #
  # • الوظيفة: استبدال وتحديث الحقول المعدلة لسجل موجود وحفظها نهائياً.
  # • متى تستخدمها؟
  #   - في كل مسارات التعديل (مسارات PUT و PATCH في الـ API).
  # • مثال عملي:
  #   تعديل رقم هاتف مريض، تعديل وصف دور وظيفي، أو تعديل سعر فحص في المختبر.
  # =========================================================================
  def update(
      self, db_obj: ModelType, update_data: Dict[str, Any]
  ) -> ModelType:
    for key, value in update_data.items():
      setattr(db_obj, key, value)
    # تعديل القيم الجديدة ديناميكياً على الكائن

    self.db.commit()
    # تثبيت التعديلات في قاعدة البيانات

    self.db.refresh(db_obj)
    # تحديث الكائن ليعكس أحدث بيانات من القاعدة

    return db_obj
    # إرجاع الكائن المحدث




    # =========================================================================
  # 6. دالة تحديث البيانات في الذاكرة دون Commit
  # =========================================================================
  


  # =========================================================================
  # 7. دالة التثبيت اليدوي المشترك (commit)
  #
  # • الوظيفة: حفظ وتثبيت كافة العمليات المفتوحة في الجلسة دفعة واحدة.
  # • متى تستخدمها؟
  #   - في طبقة الـ Service عند انتهاء كل خطوات العملية المركبة بنجاح.
  # • مثال عملي:
  #   بعد الانتهاء من إنشاء المدير والمنشأة والفرع معاً عبر دالة create_without_commit.
  # =========================================================================
  def commit(self):
    self.db.commit()

  # =========================================================================
  # 8. دالة التراجع الفوري (rollback)
  #
  # • الوظيفة: إلغاء ومسح كل التغييرات المؤقتة التي تمت في الجلسة وإعادة القاعدة لما كانت عليه.
  # • متى تستخدمها؟
  #   - داخل كتلة except في طبقة الـ Service عند حدوث أي خطأ في أي خطوة لحماية البيانات.
  # • مثال عملي:
  #   إذا فشل إنشاء المنشأة بعد إنشاء حساب المدير، ننفذ rollback فوراً لإلغاء المدير أيضاً.
  # =========================================================================
  def rollback(self):
    self.db.rollback()

  # =========================================================================
  # 9. دالة التحديث في الذاكرة (refresh)
  #
  # • الوظيفة: إعادة تحميل ومزامنة بيانات كائن معين من قاعدة البيانات بعد الـ Commit اليدوي.
  # • متى تستخدمها؟
  #   - بعد استدعاء دالة commit() اليدوية لقراءة المعرفات النهائية للكائن قبل إرجاعه للواجهة.
  # =========================================================================
  def refresh(self, instance: ModelType):
    self.db.refresh(instance)

  def flush(self):
        """تفريغ التغييرات إلى قاعدة البيانات وتوليد المعرفات الأولية بدون إنهاء المعاملة"""
        self.db.flush()